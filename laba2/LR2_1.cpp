#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <locale.h>
#include <conio.h>

/*
Вычислить площадь трапеции по формуле
S=c∙h,c=(a+b)/2, где h - высота трапеции, c - средняя линия трапеции: c=(a+b)/2, где a,b - основания трапеции
*/
int main() {
    setlocale(LC_ALL, "Rus"); // Для вывода на русском языке
    /*a - основание трапеции, b - основнвание трапеции, h - Высота трапеции, c - средняя линия трапеции, S - площадь трапеции*/
    double a, b, h, c, S; 
    

    // Ввод оснований трапеции
    printf("Введите основания трапеции a и b: ");
    scanf("%lf %lf", &a, &b);

    // Ввод высоты трапеции
    printf("Введите высоту трапеции h: ");
    scanf("%lf", &h);

    
    c = (a + b) / 2;    // Вычисление средней линии

    S = c * h;    // Вычисление площади


    printf("Площадь трапеции S: %lf\n", S);    // Вывод результата вычесления площади трапеции по формуле

    printf("Нажмите любую клавишу для окончания работы\n");
    _getch();
}
