/* Вычисление y=f(x) для заданного x по двум формулам */
#define _CRT_SECURE_NO_WARNINGS
#define PI 3.141593
#include <stdio.h>
#include <locale.h>
#include <conio.h>
#include <math.h>

int main() {
	setlocale(LC_ALL, "Rus");	// Для вывода на русском языке
	float x, y;		// Инициализация переменных x, y

	const float A = 8.732105f;		// Инициализация константы A, т.к. число 8.732105 повторяеться в формулах

	// Вычисление y по первой формуле
	printf("Введите первое значение x (0 < x <= 1,75) ");

	scanf("%f", &x);	// Ввод переменной x
	// Вычисление y по первой формуле:
	// y = 8,732105 * |x - pi| + (sqrt(x) + pi * x) / 8,732105
	y = A * fabs(x - PI) + (sqrt(x) + PI * x) / A;		

	printf("При x = %f, y = %f\n", x, y); // Вывод результата вычисления по первой формуле

	// Вычисление y по второй формуле
	printf("\nВведите второе значение x (1,75 < x <= 2,05) ");

	scanf("%f", &x);	// Ввод переменной x
	// Вычисление y по второй формуле:
	// y = (8,732105 * x^(1/4) - e^(x-x)) / ln(x) + sin^2(x)
	y = (A * pow(x, 0.25f) - exp(x-PI)) / log(x) + pow(sin(x), 2);

	printf("При x = %f, y = %f\n", x, y);	// Вывод результата вычисления по второй формуле

	printf("Нажмите любую клавишу для окончания работы\n");
	_getch();
}
